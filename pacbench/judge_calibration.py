@dataclass(frozen=True)
class CalibrationCandidate:
    """One candidate judgment. No label field — humans label later."""

    id: str        # CAL-001 ...
    category: str  # one of CATEGORIES
    norm: Norm
    kind: str      # CURRENT | HISTORICAL
    expected: str  # the atom under judgment
    answer: str    # the assistant response to judge
    context: str   # minimum temporal/situational metadata


def _c(i: int, category: str, norm: Norm, kind: str,
       expected: str, answer: str, context: str) -> CalibrationCandidate:
    return CalibrationCandidate(id=f"CAL-{i:03d}", category=category,
                                norm=norm, kind=kind, expected=expected,
                                answer=answer, context=context)


