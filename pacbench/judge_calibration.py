"""Judge-calibration candidate pool (proceed ruling 2026-09-21, step 1).

The agent DRAFTS these atom-answer pairs; humans LABEL them. Drafting is
not labeling: there is deliberately no label, gold, or verdict field
anywhere in this module (enforced by test), and nothing here is frozen.
Balance across positive/negative and easy/nasty was aimed by authoring
design — each category mixes clear assertions, clear denials, and edge
cases — but the gold labels come from two independent humans plus
adjudication. Do NOT freeze at 200 yet: the large-life
Memcal-vs-Hindsight audit will contribute observed residuals, and the
final set is pool survivors plus those residuals.

Each candidate is exactly what the narrow judge receives (ruling Q1):
one atom (``norm`` + ``expected``), one ``answer``, and minimum
temporal/situational metadata (``kind`` + ``context``). It never sees
provider identity, scores, other atoms, or source corpus.

Categories are the co-author's eight: paraphrase, negation,
historical, declined, uncertainty, contradiction, partial, mixed
(historical+current in one answer).
"""

